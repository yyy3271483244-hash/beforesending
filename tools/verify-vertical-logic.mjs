import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { chapterIndex, chapterFromHash, companions, emptyLetter, normalizeJourneyProgress } from '../src/data/journey.mjs';
import { verticalSections, visualChapter, navigationTarget, availableChapter, keeperChapter } from '../src/data/verticalJourney.mjs';

assert.deepEqual(verticalSections.map(({ id }) => id), ['opening', 'dog', 'write', 'stamp', 'post', 'waiting', 'bureau']);
assert.equal(verticalSections.filter(({ index }) => index === keeperChapter).length, 1);
for (const keeper of companions) {
  assert.equal(visualChapter(chapterFromHash('#' + keeper.id)), keeperChapter);
  const progress = normalizeJourneyProgress({ confirmedAdministrator: keeper.id });
  assert.equal(availableChapter(emptyLetter, keeper.id, progress), chapterIndex('write'));
  assert.equal(navigationTarget(chapterIndex('post'), emptyLetter, keeper.id, progress), chapterIndex('write'));
}
assert.equal(navigationTarget(chapterIndex('write'), emptyLetter, null, normalizeJourneyProgress()), keeperChapter);
assert.equal(navigationTarget(chapterIndex('bureau'), emptyLetter, null, normalizeJourneyProgress()), chapterIndex('bureau'));
const app = readFileSync(new URL('../src/components/HorizontalJourney.jsx', import.meta.url), 'utf8');
assert.equal((app.match(/<JourneyCompanion\b/g) || []).length, 1);
assert.match(app, /verticalSections\.map/);
assert.doesNotMatch(app, /useHorizontalJourney|aria-hidden=\{index !== chapter\}/);
assert.equal(existsSync(new URL('../src/animation/useHorizontalJourney.js', import.meta.url)), false);
const scroll = readFileSync(new URL('../src/animation/useVerticalJourney.js', import.meta.url), 'utf8');
assert.doesNotMatch(scroll, /scrollLeft|xPercent/);
assert.doesNotMatch(scroll, /preventDefault|guardWheel|scrollBoundary|setTimeout/);
assert.doesNotMatch(scroll, /ScrollTrigger|snapTo|autoAlpha|filter:|scale:|gsap/);
const sceneCss = readFileSync(new URL('../src/scene-system.css', import.meta.url), 'utf8');
assert.match(sceneCss, /\.journey-scene-frame \{ position: relative/);
assert.doesNotMatch(sceneCss, /position: fixed|opacity: 0/);
const desk = readFileSync(new URL('../src/animation/useDeskPaper.js', import.meta.url), 'utf8');
assert.doesNotMatch(desk, /scaleX|scaleY|scrollThreshold/);
assert.match(desk, /useState\('desk'\)/);
assert.match(desk, /locked\.current = false; changePhase\('desk'\)/);
assert.doesNotMatch(desk, /preventDefault|setTimeout|passive: false/);
const writing = readFileSync(new URL('../src/components/JourneyWriting.jsx', import.meta.url), 'utf8');
assert.equal((writing.match(/ref=\{paper\}/g) || []).length, 1);
assert.match(writing, /single pauseMarks/);
assert.match(writing, /'document'/);
assert.match(writing, /paper-top/);
assert.match(writing, /paper-body/);
assert.match(writing, /paper-bottom/);
assert.ok(writing.indexOf('className="writing-notes"') > writing.indexOf('className="paper-bottom-details"'));
const keeper = readFileSync(new URL('../src/components/JourneyCompanion.jsx', import.meta.url), 'utf8');
assert.match(keeper, /data-keeper-stage=\{stage\}/);
assert.match(keeper, /enterStage\('confirming'\)/);
assert.match(keeper, /enterStage\('confirmed'\)/);
assert.match(keeper, /inert=\{!ready \? true : undefined\}/);
assert.match(keeper, /enter\('write', event\)/);
assert.match(keeper, /enter\('read', event\)/);
assert.doesNotMatch(keeper, /keeper-personality|profile\.title|<p>Before Sending/);
assert.doesNotMatch(app, /choiceTimer|confirmAdministrator/);
const home = readFileSync(new URL('../src/components/HomeArtwork.jsx', import.meta.url), 'utf8');
assert.doesNotMatch(home, /restored-home-description|在寄出之前|写信台/);
assert.match(home, /home-original\.png/);
const motion = readFileSync(new URL('../src/animation/useHomeMotion.js', import.meta.url), 'utf8');
assert.doesNotMatch(motion, /preventDefault|ScrollTrigger|addEventListener\(['"]wheel/);
assert.match(motion, /prefers-reduced-motion/);
console.log('Passed: one keeper scene, native document-flow scrolling without wheel locks or snap, delivery navigation gates, growing paper and original art.');
